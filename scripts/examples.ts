import { execSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, extname, join } from 'node:path'

// Vendors shadcn-vue's own component examples into playground/examples, so the
// playground demos every variant without us writing (or maintaining) them.
// Like src/ui, playground/examples is generated: never edit it by hand.

const REPO = 'https://github.com/unovue/shadcn-vue.git'
const BASE = 'apps/v4/registry/bases/reka'

const root = join(import.meta.dirname, '..')
const out = join(root, 'playground', 'examples')
const checkout = join(tmpdir(), 'chassis-ui-upstream')

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const installed = new Set([
  ...Object.keys(pkg.dependencies ?? {}),
  ...Object.keys(pkg.peerDependencies ?? {}),
  ...Object.keys(pkg.devDependencies ?? {}),
])

function fetchUpstream(): string {
  rmSync(checkout, { recursive: true, force: true })
  execSync(`git clone -q --depth 1 --filter=blob:none --sparse ${REPO} "${checkout}"`, { stdio: 'inherit' })
  execSync(`git -C "${checkout}" sparse-checkout set ${BASE}/examples ${BASE}/components/example`, { stdio: 'inherit' })
  return execSync(`git -C "${checkout}" rev-parse --short HEAD`).toString().trim()
}

function rewrite(source: string): string {
  return source
    .replace(/(['"])@\/registry\/bases\/reka\/ui\/([\w-]+)\1/g, '$1chassis-ui/$2$1')
    .replace(/(['"])@\/components\/ui\/([\w-]+)\1/g, '$1chassis-ui/$2$1')
    .replace(/(['"])[~@]\/registry\/bases\/reka\/components\/example\1/g, '$1@playground/examples/_shared/example$1')
    .replace(/(['"])@\/components\/IconPlaceholder\.vue\1/g, '$1@playground/components/IconPlaceholder.vue$1')
    .replace(/(['"])[~@]\/registry\/bases\/reka\/examples\//g, '$1@playground/examples/')
}

function importsOf(source: string): string[] {
  // Real import statements only: skip the template and code samples held in template strings
  const code = source.replace(/<template>[\s\S]*<\/template>/, '').replace(/`[^`]*`/g, '``')
  const pattern = /^\s*(?:import|export)\b[^'"`;]*?\bfrom\s*['"]([^'"]+)['"]|^\s*import\s*['"]([^'"]+)['"]|\bimport\(\s*['"]([^'"]+)['"]\s*\)/gm

  return [...code.matchAll(pattern)].map(m => m[1] ?? m[2] ?? m[3])
}

function isSupported(specifier: string): boolean {
  if (specifier.startsWith('.') || specifier.startsWith('@playground/') || specifier.startsWith('chassis-ui/')) return true
  if (specifier.startsWith('@/') || specifier.startsWith('~/')) return false

  const parts = specifier.split('/')
  const name = specifier.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0]
  return name === 'vue' || installed.has(name)
}

const sha = fetchUpstream()
const upstream = join(checkout, BASE, 'examples')

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
cpSync(join(checkout, BASE, 'components', 'example'), join(out, '_shared', 'example'), { recursive: true })

const demos: Record<string, string[]> = {}
const skipped: string[] = []

for (const name of readdirSync(upstream).sort()) {
  const dir = join(upstream, name)
  if (extname(name)) continue

  // Same-folder imports become relative, so index pages and helpers are detected alike
  const files = new Map<string, string>()
  for (const file of readdirSync(dir)) {
    if (!['.vue', '.ts'].includes(extname(file))) continue
    files.set(file, rewrite(readFileSync(join(dir, file), 'utf8')).replaceAll(`@playground/examples/${name}/`, './'))
  }

  // Drop files that need a package we don't ship, then anything that imports them.
  let dropped = [...files].filter(([, src]) => !importsOf(src).every(isSupported)).map(([file]) => file)
  while (dropped.length) {
    for (const file of dropped) {
      files.delete(file)
      skipped.push(`${name}/${file}`)
    }
    const gone = dropped.map(file => basename(file, extname(file)))
    dropped = [...files]
      .filter(([, src]) => importsOf(src).some(s => s.startsWith('./') && gone.includes(basename(s, extname(s)))))
      .map(([file]) => file)
  }

  // Files another example imports (variants pulled into an index page, data, highlighters)
  // are rendered through that file, so only the top-level files are demos.
  const helpers = new Set([...files.values()].flatMap(importsOf).filter(s => s.startsWith('./')).map(s => basename(s, extname(s))))

  mkdirSync(join(out, name), { recursive: true })
  for (const [file, src] of files) writeFileSync(join(out, name, file), src)

  const list = [...files.keys()]
    .filter(file => extname(file) === '.vue' && !helpers.has(basename(file, '.vue')))
    .map(file => basename(file, '.vue'))
  if (list.length) demos[name] = list
}

writeFileSync(join(out, 'index.ts'), `// Generated by scripts/examples.ts from shadcn-vue@${sha}. Do not edit.

export const demos: Record<string, string[]> = ${JSON.stringify(demos, null, 2)}
`)

rmSync(checkout, { recursive: true, force: true })

const count = Object.values(demos).flat().length
console.log(`Vendored ${count} demos for ${Object.keys(demos).length} components from shadcn-vue@${sha}`)
if (skipped.length) console.log(`Skipped (need packages we don't ship): ${skipped.join(', ')}`)
